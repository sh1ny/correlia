import 'dart:io';
import 'dart:math';

import 'package:args/command_runner.dart';

/// A fresh cryptographically secure password (32 URL-safe characters).
String generateSecurePassword([Random? random]) {
  const alphabet =
      'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
  final source = random ?? Random.secure();
  return String.fromCharCodes([
    for (var i = 0; i < 32; i++)
      alphabet.codeUnitAt(source.nextInt(alphabet.length)),
  ]);
}

/// `tool setup`: makes sure the local, gitignored passwords file exists.
///
/// Creates [passwordsFile] with random `development` and `test` passwords when
/// it is missing. An existing file is never rewritten: when it lacks a needed
/// section the command fails, naming the file and the section.
class SetupCommand extends Command<int> {
  /// Creates the command.
  SetupCommand({
    required this.passwordsFile,
    required this.generatePassword,
    required this.out,
    required this.err,
  });

  /// Sections every local run needs.
  static const requiredSections = ['development', 'test'];

  /// The passwords file (`correlia_server/config/passwords.yaml`).
  final File passwordsFile;

  /// Produces one password; injected so tests are deterministic.
  final String Function() generatePassword;

  /// Receives progress messages (never password values).
  final StringSink out;

  /// Receives failures.
  final StringSink err;

  @override
  String get name => 'setup';

  @override
  String get description =>
      'Create the local passwords file when missing; never overwrite it.';

  @override
  Future<int> run() async {
    if (!passwordsFile.existsSync()) {
      passwordsFile.parent.createSync(recursive: true);
      passwordsFile.writeAsStringSync(_render());
      await Process.run('chmod', ['600', passwordsFile.path]);
      out.writeln('created ${passwordsFile.path}');
      return 0;
    }
    final text = passwordsFile.readAsStringSync();
    final missing = [
      for (final section in requiredSections)
        if (!RegExp('^$section:', multiLine: true).hasMatch(text)) section,
    ];
    if (missing.isNotEmpty) {
      for (final section in missing) {
        err.writeln(
          'FAIL ${passwordsFile.path}: missing the `$section` section '
          '(the file is left unchanged; add it by hand)',
        );
      }
      return 1;
    }
    out.writeln('kept ${passwordsFile.path}');
    return 0;
  }

  String _render() =>
      '''
# Local passwords for Correlia. Generated by `mise run setup`; not under version
# control. Production secrets come from SERVERPOD_PASSWORD_* environment variables.

development:
  database: "${generatePassword()}"
  serviceSecret: "${generatePassword()}"

test:
  database: "${generatePassword()}"
''';
}
